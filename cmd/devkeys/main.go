// Command devkeys prints a fresh .env for the local compose stack: an Ed25519 key pair for user
// tokens, a service-token secret and a webhook secret. Keys are generated per machine and never
// committed: `make keys` writes deploy/compose/.env (git-ignored).
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
)

func main() {
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	b64 := base64.StdEncoding.EncodeToString
	fmt.Println("# generated by `go run ./cmd/devkeys` for local development only")
	fmt.Println("AUTH_PRIVATE_KEY=" + b64(priv.Seed()))
	fmt.Println("AUTH_PUBLIC_KEY=" + b64(pub))
	fmt.Println("SERVICE_TOKEN_SECRET=" + random(32))
	fmt.Println("PSP_WEBHOOK_SECRET=whsec_" + random(24))
	fmt.Println("PSP_API_KEY=sk_test_" + random(16))
	fmt.Println("LAB_TOKEN=" + random(16))
}

func random(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return hex.EncodeToString(b)
}
